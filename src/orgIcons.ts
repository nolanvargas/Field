export function resolveOrgTaskIcon(name: string | undefined): LucideIcon {
	if (name && name in ICON_MAP) {
		return ICON_MAP[name as OrgTaskIconName];
	}
	if (name && name in LEGACY_ICON_MAP) {
		return LEGACY_ICON_MAP[name];
	}
	return CircleHelp;
}

export function isOrgTaskIconName(name: string): name is OrgTaskIconName {
	return (ORG_TASK_ICON_NAMES as readonly string[]).includes(name);
}
